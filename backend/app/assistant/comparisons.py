"""Backend-owned comparison retrieval followed by tool-free answer drafting."""

import re
import textwrap
from pathlib import Path
from typing import Annotated

from openai import AsyncOpenAI
from pydantic import Field
from pydantic_ai import Agent, ModelRetry, RunContext, ToolOutput
from pydantic_ai.models.openai import OpenAIChatModel
from pydantic_ai.providers.openai import OpenAIProvider

from app.assistant.comparison_citations import ComparisonFact
from app.assistant.deps import DocumentAgentDeps
from app.assistant.model_settings import StopAtOutputLimit, bounded_settings
from app.assistant.outputs import Contract, GapReason, GroundedAnswer
from app.assistant.selection import RequestedGap, final_answer
from app.assistant.tools import compare_filings
from app.retrieval.types import SearchFilters


def request_spans(question: str) -> dict[str, str]:
    spans = []
    for sentence in re.split(r"(?<=[.!?;])\s+|\n+", question):
        spans.extend(
            textwrap.wrap(
                sentence,
                width=1000,
                expand_tabs=False,
                replace_whitespace=False,
                break_on_hyphens=False,
            )
        )
    if len(spans) > 40:
        spans = textwrap.wrap(
            question,
            width=1000,
            expand_tabs=False,
            replace_whitespace=False,
            break_on_hyphens=False,
        )
    return {f"R{i}": text for i, text in enumerate(spans, 1)}


class ComparisonReady(Contract):
    evidence: str


class ComparisonGap(Contract):
    request_id: str = Field(min_length=2, max_length=12)
    target: SearchFilters | None = None
    reason: GapReason
    missing_detail: str = Field(min_length=1, max_length=400)


async def prepare_comparison(
    ctx: RunContext[DocumentAgentDeps],
    query: str,
    targets: Annotated[list[SearchFilters], Field(min_length=1, max_length=25)],
) -> ComparisonReady:
    """Plan an explicit filing comparison and retrieve all targets once.

    This ends planning. The backend hands evidence to a tool-free writer;
    no subsequent search/read loop is available.
    """
    total = sum(
        len(target.corpus_years or [None]) * len(target.fiscal_years or [None])
        for target in targets
    )
    if not 1 <= total <= 25:
        raise ModelRetry("Comparison requires 1–25 individual company/year targets.")
    registry = ctx.deps.registry
    shown = len(registry.displayed_ids)
    evidence = await compare_filings.__wrapped__(ctx, query, targets)
    if not registry.comparison_targets:
        raise ModelRetry("Comparison requires 1–25 individual targets.")
    registry.comparison_evidence_ids = list(
        dict.fromkeys(registry.displayed_ids[shown:])
    )
    registry.request_spans = request_spans(ctx.deps.question)
    return ComparisonReady(evidence=evidence)


def final_comparison_answer(
    ctx: RunContext[DocumentAgentDeps],
    claims: list[ComparisonFact],
    gaps: list[ComparisonGap],
) -> GroundedAnswer:
    """Submit cited per-filing facts and requested-aspect gaps.

    Trends, urgency and cross-company assessments are gaps, not claims.
    Missing company/year coverage is generated by the backend, not the model.
    """
    resolved = []
    for gap in gaps:
        quote = ctx.deps.registry.request_spans.get(gap.request_id)
        if quote is None:
            raise ModelRetry("Unknown request ID; select a displayed R ID.")
        resolved.append(
            RequestedGap(
                target=gap.target,
                reason=gap.reason,
                missing_detail=gap.missing_detail,
                request_quote=quote,
            )
        )
    if not ctx.deps.prune_unverified:
        return final_answer(ctx, claims, resolved)
    selected = []
    withheld = []
    rejection = None
    for index, claim in enumerate(claims):
        try:
            # Runs the per-claim submission checks, such as displayed evidence IDs.
            final_answer(ctx, [claim], [])
        except ModelRetry as error:
            withheld.append(index)
            rejection = rejection or error
            continue
        selected.append(claim)
    if rejection and not selected:
        # Withholding trims a failed answer; it never turns one into "no evidence".
        raise rejection
    answer = final_answer(ctx, selected, resolved)
    if withheld:
        # Indices into the submitted claims only: messages may carry model or source text.
        ctx.deps.withheld.append(
            {"stage": "withheld", "source": "submission", "claims": withheld}
        )
    return answer


def build_comparison_writer(
    settings, client: AsyncOpenAI
) -> Agent[DocumentAgentDeps, GroundedAnswer]:
    # Reuse schema preparation without a module-level agent/comparison import cycle.
    from app.assistant.agent import EvidenceChoices

    return Agent(
        OpenAIChatModel(
            settings.openai_chat_model, provider=OpenAIProvider(openai_client=client)
        ),
        deps_type=DocumentAgentDeps,
        capabilities=[EvidenceChoices(), StopAtOutputLimit("answering")],
        output_type=ToolOutput(
            final_comparison_answer, name="final_result", strict=True
        ),
        retries={"output": 0, "tools": 0},
        instructions=Path(__file__)
        .with_name("comparison-instructions.md")
        .read_text(encoding="utf-8"),
        model_settings={
            **bounded_settings(
                settings.openai_chat_model,
                settings.assistant_output_tokens,
                settings.assistant_reasoning_effort,
            ),
            "parallel_tool_calls": False,
        },
    )
